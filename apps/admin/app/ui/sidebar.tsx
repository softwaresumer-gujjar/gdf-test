'use client';

import Link from 'next/link';
import { usePathname } from 'next/navigation';
import { createClient } from '../lib/supabase/client';
import { useRouter } from 'next/navigation';

const nav = [
  { label: 'Dashboard',  href: '/dashboard',  icon: GridIcon },
  { label: 'Analytics',  href: '/analytics',  icon: ChartIcon },
  { label: 'Products',   href: '/products',   icon: BoxIcon },
  { label: 'Offers',     href: '/offers',     icon: TagIcon },
  { label: 'Inventory',  href: '/inventory',  icon: LayersIcon },
  { label: 'Orders',     href: '/orders',     icon: ShoppingBagIcon },
  { label: 'Sales',      href: '/sales',      icon: TrendingIcon },
  { label: 'Customer',   href: '/customer',   icon: UsersIcon },
  { label: 'Newsletter', href: '/newsletter', icon: MailIcon },
  { label: 'Settings',   href: '/settings',   icon: SettingsIcon },
];

export default function Sidebar() {
  const pathname = usePathname();
  const router = useRouter();

  async function signOut() {
    const supabase = createClient();
    await supabase.auth.signOut();
    router.push('/login');
  }

  return (
    <aside className="sidebar">
      {/* Logo */}
      <div className="sidebar__logo">
        <div className="sidebar__logo-icon">G</div>
        <span className="sidebar__logo-text">GDF</span>
      </div>

      {/* Nav */}
      <nav className="sidebar__nav">
        {nav.map(({ label, href, icon: Icon }) => {
          const active = pathname === href || pathname.startsWith(href + '/');
          return (
            <Link
              key={href}
              href={href}
              className={`sidebar__item${active ? ' sidebar__item--active' : ''}`}
            >
              <Icon />
              <span>{label}</span>
            </Link>
          );
        })}
      </nav>

      {/* Sign out */}
      <button className="sidebar__signout" onClick={() => { void signOut(); }}>
        <LogoutIcon />
        <span>Sign out</span>
      </button>
    </aside>
  );
}

